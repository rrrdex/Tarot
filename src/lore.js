// 只回傳 id 與標題，內容一律在資料庫分頁的共用知識裡，不在每張牌重複
export function getCardLore(card) {
  if (!card || !card.suit) return [];
  const ids = card.suit === 'Major Arcana'
    ? ['major-origin', 'major-arcana']
    : [`suit-${card.suit.toLowerCase()}`, COURT_NAMES[card.number] ? `court-${card.number.toLowerCase()}` : `number-${card.number.toLowerCase()}`];
  for (const sym of symbolLore) if (sym.cards.includes(card.nameKey)) ids.push(sym.id);
  return ids.map(libraryItem).filter(Boolean);
}
