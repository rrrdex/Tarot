// o.sx / o.sy 壓扁成透視（平放在地上的幣），o.rot 旋轉
export function coin(x, y, r, o = {}) {
  const sx = o.sx ?? 1;
  const sy = o.sy ?? 1;
  const w = f(Math.max(0.55, r * 0.075));
  const inner = FC(0, 0, r, '#a07a36') + FC(0, 0, f(r * 0.86), '#dcb662') +
    HL(`M${f(-r * 0.8)} ${f(-r * 0.1)}A${f(r * 0.81)} ${f(r * 0.81)} 0 0 1 ${f(r * 0.1)} ${f(-r * 0.8)}A${f(r * 0.95)} ${f(r * 0.95)} 0 0 0 ${f(-r * 0.8)} ${f(-r * 0.1)}Z`, 0.45) +
    F(starD(0, 0, r * 0.62, r * 0.25, 5), '#f4dc98') +
    L(`M${f(-r * 0.7)} 0a${f(r * 0.7)} ${f(r * 0.7)} 0 1 0 ${f(r * 1.4)} 0a${f(r * 0.7)} ${f(r * 0.7)} 0 1 0 ${f(-r * 1.4)} 0`, '#8a6428', w) +
    L(pentagramD(0, 0, r * 0.62), '#8a6428', w);
  const tr = `translate(${x} ${y})${o.rot ? ` rotate(${o.rot})` : ''}${sx !== 1 || sy !== 1 ? ` scale(${sx} ${sy})` : ''}`;
  return G(tr, inner);
}

// 三次貝茲曲線取樣，供 limb / sleeve 使用（轉折處較圓順）
const cubic = (p0, p1, p2, p3, n = 12) => Array.from({ length: n + 1 }, (_, i) => {
  const t = i / n;
  const u = 1 - t;
  return [0, 1].map(k => u * u * u * p0[k] + 3 * u * u * t * p1[k] + 3 * u * t * t * p2[k] + t * t * t * p3[k]);
});

