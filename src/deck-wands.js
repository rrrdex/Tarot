// 權杖：一根筆直的木杖，杖身冒出幾片小綠葉、杖頂抽出新芽（整組十四張共用）
// 由杖底 p0 畫到杖頂 p1，w 為杖身粗細
const WOOD = '#8a6440';
const WOOD_DARK = '#5f4733';
const WOOD_LIGHT = '#b08a5e';
const LEAF = '#6f8250';
const LEAF_LIGHT = '#8fa463';
function wand(p0, p1, w = 4.4) {
  const len = f(Math.hypot(p1[0] - p0[0], p1[1] - p0[1]));
  const deg = f(Math.atan2(p1[0] - p0[0], -(p1[1] - p0[1])) * 180 / Math.PI);
  const lf = f(w * 1.9);
  const leaves = [[0.24, 1], [0.46, -1], [0.66, 1], [0.84, -1]]
    .map(([t, s]) => leafD(f(s * w * 0.4), f(-len * t), lf, s * 44, 0.36)).join('');
  const tip = leafD(f(-w * 0.1), f(-len + w * 0.2), f(lf * 0.95), -24, 0.36) + leafD(f(w * 0.1), f(-len + w * 0.2), f(lf * 0.95), 24, 0.36);
  const inner = L(`M0 0V${-len}`, WOOD_DARK, f(w + 1.3)) + L(`M0 0V${-len}`, WOOD, w) +
    L(`M${f(-w * 0.2)} ${f(-w * 0.5)}V${f(-len + w * 0.5)}`, WOOD_LIGHT, f(w * 0.26)) +
    Ln(`M${f(-w / 2)} ${f(-len * 0.35)}q${f(w / 2)} ${f(w * 0.3)} ${w} 0M${f(-w / 2)} ${f(-len * 0.75)}q${f(w / 2)} ${f(w * 0.3)} ${w} 0`, WOOD_DARK, 0.8) +
    F(tip, LEAF_LIGHT) + F(leaves, LEAF);
  return G(`translate(${f(p0[0])} ${f(p0[1])}) rotate(${deg})`, inner);
}
