// 桂冠環：沿橢圓排列的葉子；half 取 'back'（上半，畫在杖後）或 'front'
function laurelRing(cx, cy, rx, ry, half) {
  let d = '';
  for (let i = 0; i < 18; i++) {
    const t = (i + 0.5) * Math.PI / 9;
    const back = Math.sin(t) < 0;
    if ((half === 'back') !== back) continue;
    const x = f(cx + rx * Math.cos(t));
    const y = f(cy + ry * Math.sin(t));
    d += leafD(x, y, 6.5, f(Math.atan2(-rx * Math.sin(t), -ry * Math.cos(t)) * 180 / Math.PI), 0.42);
  }
  const arc = half === 'back' ? `M${cx - rx} ${cy}A${rx} ${ry} 0 0 1 ${cx + rx} ${cy}` : `M${cx - rx} ${cy}A${rx} ${ry} 0 0 0 ${cx + rx} ${cy}`;
  return L(arc, '#55703c', 1.6) + F(d, half === 'back' ? '#5d7a40' : '#6f8a4c');
}
