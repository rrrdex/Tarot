const MINOR_SCENE = { ...WANDS_SCENE, ...CUPS_SCENE, ...SWORDS_SCENE, ...PENTACLES_SCENE };
let clipSeq = 0;

const RANK = { 'Ace': 1, 'Two': 2, 'Three': 3, 'Four': 4, 'Five': 5, 'Six': 6, 'Seven': 7, 'Eight': 8, 'Nine': 9, 'Ten': 10, 'Page': 11, 'Knight': 12, 'Queen': 13, 'King': 14 };
const ROMAN = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X'];
export function getCardArt(card, extraClass = '') {
  if (!card || !card.suit) return null;
  const title = (card.englishName || '').toUpperCase();
  const scene = card.suit === 'Major Arcana' ? MAJOR_SCENE[card.nameKey] : MINOR_SCENE[card.nameKey];
  if (!scene) return null;
  const id = `dk-arch-${++clipSeq}`;
  beginScene(id);
  const rank = RANK[card.number];
  // 大牌標羅馬數字；數字牌標 I–X；宮廷牌改標花色的元素符號
  const label = card.suit === 'Major Arcana' ? card.number : rank <= 10 ? ROMAN[rank] : '';
  const inner = `<clipPath id="${id}"><path d="${ARCH}"/></clipPath><g class="dk-scene" clip-path="url(#${id})">${scene().join('')}</g>${P(ARCH)}`;
  return `<svg class="card-image line-art${extraClass ? ' ' + extraClass : ''}" viewBox="0 0 300 519" xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${frame(label, title, card.suit, true)}${inner}</svg>`;
}

// 獨立的 SVG 圖檔（分享圖用）讀不到頁面的樣式表：把 style.css 裡 svg.line-art 的規則抄一份寫進去，
// 牌框顏色則用呼叫端傳入的目前主題色。小尺寸時與小縮圖一樣省略細節與文字
const STANDALONE_CSS = '*{vector-effect:non-scaling-stroke}.dk-t{stroke-width:.8}.dk-b{stroke-width:2}' +
  '.dk-g{stroke:var(--deck-gold)}.dk-gf{fill:var(--deck-gold);stroke:none}.dk-if{fill:currentColor;stroke:none}' +
  '.dk-tf{fill:var(--deck-tint)}.dk-pf{fill:var(--deck-paper)}.dk-dot{stroke-width:2;stroke-dasharray:0 6}' +
  'text{fill:currentColor;stroke:none;font-family:Didot,"Bodoni 72","Bodoni MT",Georgia,serif}.dk-ptxt{fill:var(--deck-paper)}' +
  '.dk-scene{--deck-paper:#fbf8f1;--deck-tint:#f6efe0;--deck-gold:#c49a4f;color:#2b2833}.dk-lim{vector-effect:none}';
export function getCardArtImage(card, colors, small = false) {
  const svg = getCardArt(card);
  if (!svg) return null;
  const vars = ['paper', 'tint', 'ink', 'gold'].map(k => `--deck-${k}:${colors[k]}`).join(';');
  const css = `svg{${vars};color:var(--deck-ink)}${STANDALONE_CSS}${small ? '.dk-d,text{display:none}' : ''}`;
  return svg.replace('<svg ', '<svg width="300" height="519" ')
    .replace(/(<svg[^>]*>)/, `$1<style>${css}</style><rect width="300" height="519" rx="6" fill="${colors.paper}" stroke="none"/>`);
}
