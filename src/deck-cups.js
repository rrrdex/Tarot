// 正面站姿的長袍身軀：肩寬 shW、下襬寬 hemW；頭與手臂由各牌另畫
function gown(x, sh, hem, color, deep, o = {}) {
  const w0 = o.shW || 13;
  const w1 = o.hemW || 21;
  const sw = o.sway || 0;
  const mid = f(sh + (hem - sh) * 0.4);
  const [hl, hr] = [x - w1 + sw, x + w1 + sw];
  const d = `M${x - w0} ${sh}C${x - w0 - 3} ${mid} ${hl + 1 - sw * 0.4} ${hem - 20} ${hl} ${hem}Q${x + sw} ${hem + 3} ${hr} ${hem}C${hr - 1 - sw * 0.4} ${hem - 20} ${x + w0 + 3} ${mid} ${x + w0} ${sh}Q${x} ${sh - 5} ${x - w0} ${sh}Z`;
  return GF(d, color, deep) +
    SH(`M${x + 4} ${sh - 2}L${x + w0} ${sh}C${x + w0 + 3} ${mid} ${hr - 1 - sw * 0.4} ${hem - 20} ${hr} ${hem}H${x + 8 + sw}C${x + 8 + sw * 0.6} ${hem - 40} ${x + 6} ${mid} ${x + 4} ${sh - 2}Z`, 0.1) +
    Ln(`M${x - 6} ${sh + 30}L${x - 9 + sw} ${hem - 2}M${x + 5} ${sh + 30}L${x + 8 + sw} ${hem - 2}`, o.fold || deep, 0.8);
}
