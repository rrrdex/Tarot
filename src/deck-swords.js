// 寶劍：鋼刃（#e2e6ea、中央刃線）、金護手、柄與柄頭
// (x, y) 為護手中心；deg 為劍尖方向（0 朝上、順時針）；len 為護手到劍尖的長度
// o.s 粗細倍率；o.cut 刃在 len 處平切（插進土裡、刺進東西時用，不畫劍尖）
export function sword(x, y, deg, len, o = {}) {
  const s = o.s || 1;
  const e = f(-len / s);
  const w = 3.2;
  const blade = o.cut ? `M${-w} 0V${e}H${w}V0Z` : `M${-w} 0V${f(e + 10)}L0 ${e}L${w} ${f(e + 10)}V0Z`;
  const right = o.cut ? `M0 0V${e}H${w}V0Z` : `M0 0V${e}L${w} ${f(e + 10)}V0Z`;
  return G(`translate(${x} ${y}) rotate(${deg}) scale(${s})`,
    F(blade, '#e2e6ea') + SH(right, 0.13) + Ln(blade, '#8f949c', 0.6) + Ln(`M0 -2.5V${f(e + (o.cut ? 1 : 11))}`, '#9aa0a8', 0.7) +
    L('M0 1.5V12', K.goldDeep, 3.4) + Ln('M-1.7 5h3.4M-1.7 8.5h3.4', '#7a5c2c', 0.6) +
    L('M-10.5 0H10.5', K.gold, 3.6) + FC(-11, 0, 2.2, K.gold) + FC(11, 0, 2.2, K.gold) + HL('M-10 -1.4H10V-0.4H-10Z', 0.35) +
    FC(0, 14.6, 3, K.gold) + HL('M-1.8 13.6a2 2 0 0 1 2.4 -1.6v1a1 1 0 0 0 -1.4 0.8Z', 0.5));
}
// 握住直立劍柄的拳頭：手背朝外，四指橫繞劍柄、拇指壓在上緣；side 為手臂伸來的一側（-1 左、1 右）
function fist(x, y, side = -1, r = 1) {
  const w = 8 * r;
  const h = 9.5 * r;
  const k = 4.5 * r;
  const X = (v) => f(x + side * v * r);
  const body = `M${f(x - w)} ${f(y - h + k)}Q${f(x - w)} ${f(y - h)} ${f(x - w + k)} ${f(y - h)}H${f(x + w - k)}Q${f(x + w)} ${f(y - h)} ${f(x + w)} ${f(y - h + k)}` +
    `V${f(y + h - k)}Q${f(x + w)} ${f(y + h)} ${f(x + w - k)} ${f(y + h)}H${f(x - w + k)}Q${f(x - w)} ${f(y + h)} ${f(x - w)} ${f(y + h - k)}Z`;
  return F(body, K.skin) + SH(`M${X(2)} ${f(y - h + 0.4)}C${X(0.5)} ${y} ${X(0.5)} ${y} ${X(2)} ${f(y + h - 0.4)}H${X(3.5)}Q${X(8)} ${f(y + h)} ${X(8)} ${f(y + h - k)}V${f(y - h + k)}Q${X(8)} ${f(y - h)} ${X(3.5)} ${f(y - h + 0.4)}Z`, 0.07) +
    // 指節彎下去之後的四指分界
    Ln([-4.6, 0, 4.6].map(v => `M${X(2)} ${f(y + v * r)}H${X(-7.6)}`).join('') + `M${X(2)} ${f(y - h + 2 * r)}C${X(0.5)} ${y} ${X(0.5)} ${y} ${X(2)} ${f(y + h - 2 * r)}`, K.skinShade, 0.8) +
    // 拇指由手背那側壓過食指
    FE(X(1.5), f(y - h + 1.6 * r), f(6.4 * r), f(2.6 * r), K.skin, -side * 6) + Ln(`M${X(7)} ${f(y - h + 3.4 * r)}Q${X(1)} ${f(y - h + 5 * r)} ${X(-4.5)} ${f(y - h + 2.2 * r)}`, K.skinShade, 0.8);
}
