const puff = (pts, fill) => pts.map(([x, y, r]) => FC(x, y, r, fill)).join('');
// 雲堤：上緣一串圓拱、下緣淺淺的波浪；h 為厚度
function bankD(x0, x1, y, h, n, k = 0) {
  const step = (x1 - x0) / n;
  let d = `M${x0} ${f(y + h)}V${y}`;
  for (let i = 1; i <= n; i++) {
    const r = f(step * (0.56 + ((i * 7 + k * 3) % 5) * 0.06));
    d += `A${r} ${r} 0 0 1 ${f(x0 + i * step)} ${f(y + (((i * 37 + k * 13) % 7) - 3))}`;
  }
  d += `V${f(y + h)}`;
  for (let i = n - 1; i >= 0; i--) d += `A${f(step * 0.62)} ${f(step * 0.62)} 0 0 1 ${f(x0 + i * step)} ${f(y + h + (((i * 29 + k * 7) % 5) - 2))}`;
  return `${d}Z`;
}

// 被風拉長的雲：右端圓鼓、左端被扯成尖細的尾巴
function streakD(x0, x1, y, h) {
  const w = x1 - x0;
  return `M${x0} ${y}C${f(x0 + w * 0.3)} ${f(y - h * 0.3)} ${f(x0 + w * 0.5)} ${f(y - h * 0.9)} ${f(x1 - h * 1.6)} ${f(y - h * 0.8)}` +
    `A${f(h * 0.8)} ${f(h * 0.8)} 0 0 1 ${f(x1 - h * 0.4)} ${f(y - h * 0.2)}A${f(h * 0.5)} ${f(h * 0.5)} 0 0 1 ${f(x1 - h * 0.6)} ${f(y + h * 0.5)}` +
    `C${f(x0 + w * 0.6)} ${f(y + h * 0.6)} ${f(x0 + w * 0.3)} ${f(y + h * 0.3)} ${x0} ${y}Z`;
}

// 王座上的浮雕：蝴蝶（上大下小兩對翅膀）與帶翅的小天使
function butterfly(x, y, s, fill, line) {
  const k = (v) => f(v * s);
  const wings = `M${x} ${y}C${f(x - k(4))} ${f(y - k(12))} ${f(x - k(14))} ${f(y - k(12))} ${f(x - k(12))} ${f(y - k(2))}C${f(x - k(10))} ${f(y + k(2))} ${f(x - k(4))} ${f(y + k(1))} ${x} ${y}Z` +
    `M${x} ${y}C${f(x + k(4))} ${f(y - k(12))} ${f(x + k(14))} ${f(y - k(12))} ${f(x + k(12))} ${f(y - k(2))}C${f(x + k(10))} ${f(y + k(2))} ${f(x + k(4))} ${f(y + k(1))} ${x} ${y}Z` +
    `M${x} ${y}C${f(x - k(3))} ${f(y + k(2))} ${f(x - k(10))} ${f(y + k(6))} ${f(x - k(7))} ${f(y + k(10))}C${f(x - k(4))} ${f(y + k(11))} ${f(x - k(1))} ${f(y + k(6))} ${x} ${y}Z` +
    `M${x} ${y}C${f(x + k(3))} ${f(y + k(2))} ${f(x + k(10))} ${f(y + k(6))} ${f(x + k(7))} ${f(y + k(10))}C${f(x + k(4))} ${f(y + k(11))} ${f(x + k(1))} ${f(y + k(6))} ${x} ${y}Z`;
  return F(wings, fill) + Ln(wings, line, 0.8) + L(`M${x} ${f(y - k(5))}V${f(y + k(7))}`, line, k(1.8)) +
    Ln(`M${x} ${f(y - k(5))}q${k(-2)} ${k(-4)} ${k(-4)} ${k(-5)}M${x} ${f(y - k(5))}q${k(2)} ${k(-4)} ${k(4)} ${k(-5)}`, line, 0.8);
}
function cherub(x, y) {
  const wings = leafD(x - 6, y + 2, 14, -70, 0.42) + leafD(x + 6, y + 2, 14, 70, 0.42);
  return F(wings, '#d6d1c8') + Ln(wings, '#77726a', 0.8) + FC(x, y, 6.4, '#ddd8cf') + Ln(`M${x} ${y}m-6.4 0a6.4 6.4 0 1 0 12.8 0a6.4 6.4 0 1 0 -12.8 0`, '#77726a', 0.8) +
    FC(x - 2.2, y - 0.6, 0.8, '#5f5a54') + FC(x + 2.2, y - 0.6, 0.8, '#5f5a54') + Ln(`M${x - 1.6} ${y + 2.6}q1.6 1.2 3.2 0`, '#5f5a54', 0.7) +
    Ln(`M${x - 5} ${y - 4}q2 -3 5 -3q3 0 5 3`, '#77726a', 0.8);
}

